def build_tab_pacing_sensitivity() -> None:
    a = pd.read_csv(RES / "exp11" / "exp11a_pacing_generality.csv")
    p = a.pivot_table(index=["gen", "coupling", "R", "J", "B", "seed"], columns=["policy", "mode"], values="gcr_pct")
    rows = []
    def add(label, idx):
        sub = p.loc[idx] if idx is not None else p
        g = sub[("past_qmass", "none")]
        u = sub[("past_qmass", "uniform")]
        sp = sub[("past_qmass", "spacing")]
        o = sub[("oracle_1blk", "uniform")]
        rows.append((label, len(sub), g.mean(), u.mean(), sp.mean(), 100 * ((u - g) > 0).mean(), 100 * ((u - g) < -1).mean(), (o - u).mean()))
    for (J, B) in [(10, 3), (10, 5), (10, 7), (20, 5), (20, 10)]:
        add(f"$J{{=}}{J}$, $B{{=}}{B}$", p.index[(p.index.get_level_values("J") == J) & (p.index.get_level_values("B") == B)])
    for c, lab in (("decoupled", "Decoupled inserts"), ("colocated", "Co-located inserts")):
        add(lab, p.index[p.index.get_level_values("coupling") == c])
    for R in (16, 64):
        add(f"$R{{=}}{R}$ shards", p.index[p.index.get_level_values("R") == R])
    add("All", None)
    df = pd.DataFrame(rows, columns=["setting", "n", "greedy", "uniform", "spacing", "win", "loss", "foresight"])
    df.to_csv(OUT_CSV / "tab_pacing_sensitivity.csv", index=False)
    lines = [
        "% Auto-generated by experiments/build_story_tables.py from exp11/exp11a_pacing_generality.csv",
        "\\begin{table}[t]", "\\centering", "\\small", "\\renewcommand{\\arraystretch}{0.9}",
        "\\caption{Pacing sensitivity for \\texttt{Past-QMass} over \\ReplayTraces{} replay traces: mean GCR (\\%) under greedy, uniform-cap, and minimum-spacing pacing; share of traces where the uniform cap gains or loses more than one point; and the extra GCR of a paced one-block oracle.}",
        "\\label{tab:pacing}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{lrrrrrrr}", "\\toprule",
        "Setting & $n$ & Greedy & Uniform & Spacing & Gain & Loss & Oracle \\\\", "\\midrule",
    ]
    for i, r in df.iterrows():
        if r["setting"] in ("Decoupled inserts", "$R{=}16$ shards", "All"):
            lines.append("\\midrule")
        pre = "\\ccrow " if r["setting"] == "All" else ""
        lines.append(f"{pre}{r['setting']} & {int(r['n'])} & {r['greedy']:.1f} & {r['uniform']:.1f} & {r['spacing']:.1f} & {r['win']:.0f}\\% & {r['loss']:.0f}\\% & +{r['foresight']:.1f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    (OUT_TEX / "tab_pacing_sensitivity.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


