def _fmt_best(vals, higher=True, fmt="{:.1f}"):
    arr = np.array(vals, dtype=float)
    order = np.argsort(-arr if higher else arr)
    out = [fmt.format(v) for v in arr]
    if len(arr) >= 1:
        out[order[0]] = "\\textbf{" + out[order[0]] + "}"
    if len(arr) >= 2:
        out[order[1]] = "\\underline{" + out[order[1]] + "}"
    return out


def build_tab_sched_live() -> None:
    m1 = pd.read_csv(OUT_CSV / "tab_m1_bridge.csv")
    keep = ["noop", "fixed_c2", "past_qmass", "ewma_a03", "gbrt_causal", "oracle_1blk"]
    m1 = m1[m1["policy"].isin(keep)].copy()
    lines = [
        "% Auto-generated by experiments/build_story_tables.py from tab_m1_bridge.csv and exp11/exp11b_paced_bridge.csv",
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\renewcommand{\\arraystretch}{0.90}",
        "\\caption{Live 16-shard scheduler bridges (unmodified engine per shard plus an exact-scan delta buffer, $B{=}5$ merges over 10 blocks). "
        "(a) Exp~9 M1 on Ryzen Core-8 with greedy spending: learned \\texttt{GBRT-Causal} and realized-history \\texttt{Past-QMass} are within 0.5\\,s. "
        "(b) Exp~11-B on Xeon NUMA-1 (one job per isolated core, w/C $\\le 1.004$): GCR (\\%) / CPU saved vs.\\ \\texttt{No-Op} (\\%), averaged over traces whose hotspot shift comes after a greedy policy has spent its budget ($n{=}9$), before it ($n{=}2$), or never ($n{=}2$). "
        "Paced variants cap cumulative spend at $\\lfloor B j/(J{-}1)\\rfloor$. GCR depends only on the schedule and is identical across engines; CPU saved is measured per engine. \\texttt{EWMA} selects the same shards as \\texttt{Past-QMass} on these traces.}",
        "\\label{tab:sched_live}",
        "\\begin{minipage}[t]{0.40\\textwidth}",
        "\\centering",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "\\multicolumn{5}{c}{\\textbf{(a) Greedy budget, Exp 9 M1 (Ryzen)}} \\\\",
        "\\midrule",
        "Engine ($n$) & Policy & CPU (s) $\\downarrow$ & GCR $\\uparrow$ & Att. \\\\",
        "\\midrule",
    ]
    disp = {"noop": "No-Op", "fixed_c2": "Fixed $c{=}2$", "past_qmass": "Past-QMass", "ewma_a03": "EWMA", "gbrt_causal": "GBRT-Causal", "oracle_1blk": "\\textit{1-blk oracle}"}
    for k, (eng, sub) in enumerate(m1.groupby("engine", sort=False)):
        sub = sub.set_index("policy").loc[[p for p in keep if p in set(sub["policy"])]].reset_index()
        elig = sub["policy"] != "oracle_1blk"
        cpu_f = ["" for _ in range(len(sub))]
        c_e = _fmt_best(sub.loc[elig, "total_cpu_s"].tolist(), higher=False, fmt="{:.2f}")
        for idx, v in zip(sub.index[elig], c_e):
            cpu_f[idx] = v
        for idx in sub.index[~elig]:
            cpu_f[idx] = "\\textit{" + f"{sub.loc[idx, 'total_cpu_s']:.2f}" + "}"
        for i, r in sub.iterrows():
            lab = f"{r['eng_disp'].replace(' (16-sh)', '')} ({int(r['n_traces'])})" if i == 0 else ""
            gcr = "--" if pd.isna(r["gcr_ops_pct"]) else f"{r['gcr_ops_pct']:.1f}"
            lines.append(f"{lab} & {disp[r['policy']]} & {cpu_f[i]} & {gcr} & {r['att_0965_pct']:.0f}\\% \\\\")
        if k == 0:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{minipage}\\hfill", "\\begin{minipage}[t]{0.58\\textwidth}", "\\centering",
              "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{llccccc}", "\\toprule",
              "\\multicolumn{7}{c}{\\textbf{(b) Pacing on live engines, Exp 11-B (Xeon): GCR / CPU saved}} \\\\", "\\midrule",
              "Engine & Hotspot shift & $c{=}2$ & PQ greedy & PQ paced & Oracle greedy & Oracle paced \\\\", "\\midrule"]
    b = pd.read_csv(RES / "exp11" / "exp11b_paced_bridge.csv")
    noop = b[b["policy"] == "noop"].set_index(["engine", "trace", "tsw"])["total_cpu_s"]
    b = b.join(noop.rename("noop_cpu"), on=["engine", "trace", "tsw"])
    b["saved"] = 100.0 * (b["noop_cpu"] - b["total_cpu_s"]) / b["noop_cpu"]
    b["grp"] = np.where(b["trace"].str.startswith("abrupt") & (b["tsw"] >= 20), "after budget", np.where(b["trace"].str.startswith("abrupt"), "before budget", "none"))
    pols = ["fixed_c2", "past_qmass", "past_qmass_paced", "oracle", "oracle_paced"]
    summ = b.groupby(["engine", "grp", "policy"])[["gcr_ops_pct", "saved"]].mean().reset_index()
    summ.to_csv(OUT_CSV / "tab_sched_live_exp11b.csv", index=False)
    edisp = {"sharded_faiss_ivf": "FAISS-IVF", "sharded_usearch": "USearch"}
    for k, eng in enumerate(["sharded_faiss_ivf", "sharded_usearch"]):
        for j, grp in enumerate(["after budget", "before budget", "none"]):
            s = summ[(summ["engine"] == eng) & (summ["grp"] == grp)].set_index("policy")
            causal = ["fixed_c2", "past_qmass", "past_qmass_paced"]
            best = s.loc[causal, "saved"].idxmax()
            cells = []
            for p in pols:
                txt = f"{s.loc[p, 'gcr_ops_pct']:.1f} / {s.loc[p, 'saved']:.1f}"
                if p == best:
                    txt = "\\textbf{" + txt + "}"
                if p.startswith("oracle"):
                    txt = "\\textit{" + txt + "}"
                cells.append(txt)
            lab = edisp[eng] if j == 0 else ""
            pre = "\\ccrow " if grp == "after budget" else ""
            lines.append(f"{pre}{lab} & {grp} & " + " & ".join(cells) + " \\\\")
        if k == 0:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{minipage}", "\\end{table*}"]
    (OUT_TEX / "tab_sched_live.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


